// Generates workflows/legacy/terracorridor.json, the old single-workflow design (reference only; W1 to W5 plus the API workflow replace it).
// One workflow so all branches share workflow static data (no extra database needed for the demo).
// Branches:
//   A. Engine run: weekly schedule, manual trigger, or POST /webhook/terracorridor/run
//      route -> segments -> 10 km cells -> Open-Meteo archive + CMIP6 climate + elevation + NASA POWER
//      -> SHA-256 of every raw response -> score -> AI explanations -> save to static data
//   B. GET  /webhook/terracorridor/corridor  -> latest corridor JSON (dashboard data)
//   C. GET  /webhook/terracorridor/map       -> the dashboard page
//   D. POST /webhook/terracorridor/action    -> approve / reject / override, appended to the audit log
// Usage: node scripts/make-workflow.js   (run scripts/build.js first)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const engine = read('src/engine.js').replace(/if \(typeof module[\s\S]*$/, '');
const demo = JSON.parse(read('data/demo/corridor.json'));
const uuid = () => crypto.randomUUID();

const nodes = [];
const connections = {};
let x = 0;
function node(name, type, typeVersion, parameters, pos, extra = {}) {
  nodes.push({ id: uuid(), name, type, typeVersion, position: pos, parameters, ...extra });
  return name;
}
function link(from, to, outIndex = 0) {
  connections[from] = connections[from] || { main: [] };
  while (connections[from].main.length <= outIndex) connections[from].main.push([]);
  connections[from].main[outIndex].push({ node: to, type: 'main', index: 0 });
}
const code = (body) => `// GENERATED by scripts/make-workflow.js from src/engine.js. Edit the source, not this node.\n${engine}\n${body.trim()}\n`;

// ---------- A. Engine run ----------
const MODELS = ['MRI_AGCM3_2_S', 'EC_Earth3P_HR', 'MPI_ESM1_2_XR'];
const tSchedule = node('Every Monday 06:00', 'n8n-nodes-base.scheduleTrigger', 1.2,
  { rule: { interval: [{ field: 'weeks', triggerAtDay: [1], triggerAtHour: 6 }] } }, [0, 0]);
const tManual = node('Run now (manual)', 'n8n-nodes-base.manualTrigger', 1, {}, [0, 200]);
const tRun = node('POST /terracorridor/run', 'n8n-nodes-base.webhook', 2,
  { httpMethod: 'POST', path: 'terracorridor/run', responseMode: 'onReceived', options: {} }, [0, 400], { webhookId: uuid() });

const nRoute = node('Route config', 'n8n-nodes-base.code', 2, { jsCode: `// Lane B: replace ROUTE with the real pipeline from Overpass (way["man_made"="pipeline"], out geom),
// as [[lon, lat], ...], and SUBSTATIONS with power=substation points. NAME shows on the dashboard.
const NAME = 'Demo corridor (illustrative route)';
const SYNTHETIC_ROUTE = true;
const ROUTE = ${JSON.stringify(demo.route)};
const SUBSTATIONS = ${JSON.stringify(demo.substations)};
return [{ json: { name: NAME, syntheticRoute: SYNTHETIC_ROUTE, route: ROUTE, substations: SUBSTATIONS } }];` }, [240, 200]);
for (const t of [tSchedule, tManual, tRun]) link(t, nRoute);

const nSeg = node('Segment route', 'n8n-nodes-base.code', 2, { jsCode: code(`
const cfgIn = $input.first().json;
return ENGINE.segmentRoute(cfgIn.route, DEFAULTS).map((s) => ({ json: s }));`) }, [480, 200]);
link(nRoute, nSeg);

const nCells = node('Group into 10 km cells', 'n8n-nodes-base.code', 2, { jsCode: `// Climate data is ~10 km resolution, so segments in the same cell share one API call.
const CELL = 10;
const segs = $input.all().map((i) => i.json);
const cells = [];
for (let i = 0; i < segs.length; i += CELL) {
  const group = segs.slice(i, i + CELL);
  const mid = group[Math.floor(group.length / 2)].mid;
  // elevation points: segment mid plus its two strip samples (3 per segment, max 100 per call)
  const pts = group.flatMap((s) => [s.mid, ...s.samples]);
  cells.push({ json: {
    cell: 'C' + (i / CELL), segIds: group.map((s) => s.id),
    lat: mid[1].toFixed(4), lon: mid[0].toFixed(4),
    elevLat: pts.map((p) => p[1]).join(','), elevLon: pts.map((p) => p[0]).join(','),
  } });
}
return cells;` }, [720, 200]);
link(nSeg, nCells);

const http = (name, url, pos) => node(name, 'n8n-nodes-base.httpRequest', 4.2,
  { url, options: { timeout: 120000 } }, pos, { retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 });
const hashNode = (name, prop, pos) => node(name, 'n8n-nodes-base.crypto', 1,
  { action: 'hash', type: 'SHA256', value: '={{ JSON.stringify($json) }}', dataPropertyName: prop }, pos);

const nArch = http('Open-Meteo archive 1995-2025',
  "=https://archive-api.open-meteo.com/v1/archive?latitude={{ $('Group into 10 km cells').item.json.lat }}&longitude={{ $('Group into 10 km cells').item.json.lon }}&start_date=1995-01-01&end_date=2025-12-31&daily=precipitation_sum,temperature_2m_min,temperature_2m_max,soil_moisture_0_to_7cm_mean&timezone=UTC",
  [960, 200]);
link(nCells, nArch);
const hArch = hashNode('SHA-256 archive', 'sha256', [1200, 200]);
link(nArch, hArch);

const nClim = http('CMIP6 climate 1995-2036',
  `=https://climate-api.open-meteo.com/v1/climate?latitude={{ $('Group into 10 km cells').item.json.lat }}&longitude={{ $('Group into 10 km cells').item.json.lon }}&start_date=1995-01-01&end_date=2036-12-31&models=${MODELS.join(',')}&daily=precipitation_sum,temperature_2m_min,temperature_2m_max,soil_moisture_0_to_10cm_mean`,
  [1440, 200]);
link(hArch, nClim);
const hClim = hashNode('SHA-256 climate', 'sha256', [1680, 200]);
link(nClim, hClim);

const nElev = http('Elevation',
  "=https://api.open-meteo.com/v1/elevation?latitude={{ $('Group into 10 km cells').item.json.elevLat }}&longitude={{ $('Group into 10 km cells').item.json.elevLon }}",
  [1920, 200]);
link(hClim, nElev);

const nSun = http('NASA POWER irradiance',
  "=https://power.larc.nasa.gov/api/temporal/climatology/point?parameters=ALLSKY_SFC_SW_DWN&community=RE&latitude={{ $('Group into 10 km cells').item.json.lat }}&longitude={{ $('Group into 10 km cells').item.json.lon }}&format=JSON",
  [2160, 200]);
link(nElev, nSun);

const nScore = node('Score corridor', 'n8n-nodes-base.code', 2, { jsCode: code(`
// Joins every API response back to its segments, scores, and saves the corridor document.
const MODELS = ${JSON.stringify(MODELS)};
const cfg = DEFAULTS;
const MODEL = null; // paste ml/model.json here to use the learned weights
const routeCfg = $('Route config').first().json;
const segs = $('Segment route').all().map((i) => i.json);
const cells = $('Group into 10 km cells').all().map((i) => i.json);
const arch = $('SHA-256 archive').all().map((i) => i.json);
const clim = $('SHA-256 climate').all().map((i) => i.json);
const elev = $('Elevation').all().map((i) => i.json);
const sun = $('NASA POWER irradiance').all().map((i) => i.json);
const byId = Object.fromEntries(segs.map((s) => [s.id, s]));
const sources = [];
const now = new Date().toISOString();
cells.forEach((c, k) => {
  const a = arch[k] || {}, cl = clim[k] || {}, el = (elev[k] || {}).elevation || [], su = sun[k];
  sources.push({ cell: c.cell, kind: 'open-meteo-archive', sha256: a.sha256 || null, fetchedAt: now });
  sources.push({ cell: c.cell, kind: 'open-meteo-cmip6', sha256: cl.sha256 || null, fetchedAt: now });
  const baseline = a.daily ? ENGINE.baselineStats(a.daily, cfg) : null;
  const byModel = cl.daily ? ENGINE.splitModels(cl.daily, MODELS) : null;
  const irr = su && su.properties ? su.properties.parameter.ALLSKY_SFC_SW_DWN.ANN : null;
  c.segIds.forEach((id, j) => {
    const s = byId[id];
    s.cell = c.cell;
    s.sourceHashes = [a.sha256 || null, cl.sha256 || null];
    s.baseline = baseline;
    s.projections = byModel && baseline ? {
      y5: ENGINE.projectedStats(byModel, baseline, cfg.horizons.y5, cfg),
      y10: ENGINE.projectedStats(byModel, baseline, cfg.horizons.y10, cfg),
    } : null;
    const e = el.slice(j * 3, j * 3 + 3); // [mid, left sample, right sample], samples 130 m from centre
    s.slopePct = e.length === 3 && e.every((v) => v != null) ? Math.round(Math.max(Math.abs(e[1] - e[0]), Math.abs(e[2] - e[0])) / 130 * 1000) / 10 : null;
    s.irradiance = irr;
    s.substationKm = routeCfg.substations.length ? Math.round(Math.min(...routeCfg.substations.map((p) => ENGINE.haversine(s.mid, p))) / 100) / 10 : null;
    s.ndvi = s.ndvi || null; // filled by the Sentinel-2 branch when it is connected
  });
});
for (const s of segs) {
  s.risk = { y5: ENGINE.riskScore(s, 'y5', cfg, MODEL), y10: ENGINE.riskScore(s, 'y10', cfg, MODEL) };
  s.build = ENGINE.buildScore(s, s.risk.y10, cfg);
  s.money = { y5: ENGINE.moneyForSegment(s.risk.y5, 5, cfg), y10: ENGINE.moneyForSegment(s.risk.y10, 10, cfg) };
}
const doc = {
  meta: { name: routeCfg.name, synthetic: !!routeCfg.syntheticRoute, note: routeCfg.syntheticRoute ? 'Illustrative route; climate, elevation and irradiance are real API data.' : 'Live n8n run', generatedAt: now, models: MODELS, method: MODEL ? 'logistic-regression' : 'weighted-rules' },
  config: cfg, route: routeCfg.route, substations: routeCfg.substations, segments: segs, sources,
  summary: { y5: ENGINE.corridorSummary(segs, cfg, { years: 5 }), y10: ENGINE.corridorSummary(segs, cfg, { years: 10 }) },
};
const store = $getWorkflowStaticData('global');
store.corridor = doc;
store.audit = store.audit || [];
store.audit.unshift({ at: now, action: 'engine_run', by: 'n8n', details: { segments: segs.length, red: doc.summary.y10.tiers.red || 0, amber: doc.summary.y10.tiers.amber || 0 } });
return [{ json: { saved: true, segments: segs.length, tiers: doc.summary.y10.tiers, top: doc.summary.y10.top.slice(0, 3) } }];`) }, [2400, 200]);
link(nSun, nScore);

const nPrompts = node('Explanation prompts', 'n8n-nodes-base.code', 2, { jsCode: `// One prompt per amber/red segment. The model may only restate our numbers.
const doc = $getWorkflowStaticData('global').corridor;
return doc.segments.filter((s) => s.risk.y10 && ['amber', 'red', 'red-uncertain'].includes(s.risk.y10.tier)).slice(0, 15).map((s) => {
  const r = s.risk.y10;
  const facts = r.drivers.slice(0, 3).map((d) => d.label + ': ' + (d.base != null ? 'baseline ' + d.base + ', projected ' + d.proj + ', ' : '') + 'change ' + d.change).join('; ');
  return { json: { id: s.id, prompt: 'You explain a pipeline corridor risk score to an operations engineer. Use only these numbers and add none. Segment ' + s.id + ', 10-year risk score ' + r.score + ' (' + r.tier + '), model agreement ' + r.agreement + '. Drivers: ' + facts + '. Slope ' + s.slopePct + '%. Write exactly two sentences: what drives the risk, and what a field crew should check first.' } };
});` }, [2640, 200]);
link(nScore, nPrompts);

