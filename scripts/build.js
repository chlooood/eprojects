// Build step. One source of truth (src/engine.js) goes into:
//   dist/dashboard.html        page n8n serves (data from window.TC_API, set by the W6 workflow)
//   dist/dashboard-demo.html   standalone page with the demo data inlined (open it in any browser)
//   dist/n8n/*.js              paste-ready bodies for n8n Code nodes
// Usage: node scripts/build.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); fs.writeFileSync(path.join(root, p), s); };

const engine = read('src/engine.js').replace(/if \(typeof module[\s\S]*$/, '');
// Works offline: Leaflet is inlined from web/vendor (BSD-2-Clause, v1.9.4) instead of loaded from a CDN.
// Fonts fall back to system fonts and map tiles stay blank without a network; the route, scores and pages still work.
const LEAFLET_JS = '<script src="https://unpkg.com/leaflet@1.9.4/dist/leaflet.js"></script>';
const LEAFLET_CSS = '<link rel="stylesheet" href="https://unpkg.com/leaflet@1.9.4/dist/leaflet.css">';
const src = read('web/dashboard.html');
if (!src.includes(LEAFLET_JS) || !src.includes(LEAFLET_CSS)) throw new Error('web/dashboard.html: Leaflet tags not found');
const inline = (tag, body) => tag + body.replace(/<\/(script|style)/gi, '<\\/$1') + '</' + tag.slice(1);
const base = src.replace('/*__ENGINE__*/', () => engine)
  .replace(LEAFLET_CSS, () => inline('<style>', read('web/vendor/leaflet.css')));
const page = (extra) => base.replace(LEAFLET_JS, () => inline('<script>', read('web/vendor/leaflet.js')) + (extra ? '\n' + extra : ''));

// dist/dashboard.html: reads the n8n feed (?api=...). If n8n cannot be reached it falls back to the snapshot below,
// a saved copy of a real n8n run (data/snapshot/live-snapshot.json), and labels itself "Offline snapshot".
const snapFile = path.join(root, 'data', 'snapshot', 'live-snapshot.json');
const snap = fs.existsSync(snapFile) ? `<script>window.TC_SNAPSHOT = ${read('data/snapshot/live-snapshot.json').replace(/<\//g, '<\\/')};</script>` : '';
const live = page(snap);
write('dist/dashboard.html', live);

// deploy/index.html: the same page with this team's n8n webhook as the default API (workflows/wiring.json, "apiBase").
const wiring = JSON.parse(read('workflows/wiring.json'));
if (wiring.apiBase) {
  const needle = "new URLSearchParams(location.search).get('api') || '';";
  if (!live.includes(needle)) throw new Error('API default not found in dashboard');
  write('deploy/index.html', live.replace(needle, () => `new URLSearchParams(location.search).get('api') || ${JSON.stringify(wiring.apiBase)};`));
}

// dist/dashboard-demo.html: the SYNTHETIC corridor inlined. No network needed at all.
const demo = read('data/demo/corridor.json').replace(/<\//g, '<\\/');
write('dist/dashboard-demo.html', page(`<script>window.TC_DATA = ${demo};</script>`));

// n8n Code node bodies. Each one starts with the engine, then does one job.
const header = `// GENERATED by scripts/build.js from src/engine.js. Edit the source, not this file.\n${engine}\n`;
const nodes = {
  '01-segment-route.js': `
// W1 Corridor setup. Input: one item with Overpass JSON (elements[].geometry). Output: one item per segment.
const way = $input.first().json.elements.filter((e) => e.geometry).sort((a, b) => b.geometry.length - a.geometry.length)[0];
if (!way) throw new Error('No pipeline geometry in the Overpass response');
const coords = way.geometry.map((g) => [g.lon, g.lat]);
return ENGINE.segmentRoute(coords, DEFAULTS).map((s) => ({ json: { ...s, osmWayId: way.id } }));
`,
  '02-baseline.js': `
// W2 Long-range engine, step 1. Input items: { segment, archive } where archive is the Open-Meteo
// /v1/archive response (daily). Output: segment with baseline stats.
return $input.all().map((it) => {
  const seg = it.json.segment, daily = it.json.archive && it.json.archive.daily;
  return { json: { ...seg, baseline: daily ? ENGINE.baselineStats(daily, DEFAULTS) : null } };
});
`,
  '03-projections.js': `
// W2 step 2. Input items: { segment (with baseline), climate } where climate is the Open-Meteo
// Climate API response for the models in MODELS, requested for 1995-01-01 to 2036-12-31 so each model
// is compared with its own history (delta method). Output: segment with projections for 5 and 10 years.
const MODELS = ['MRI_AGCM3_2_S', 'EC_Earth3P_HR', 'MPI_ESM1_2_XR'];
return $input.all().map((it) => {
  const seg = it.json.segment, daily = it.json.climate && it.json.climate.daily;
  if (!daily || !seg.baseline) return { json: { ...seg, projections: null } };
  const byModel = ENGINE.splitModels(daily, MODELS);
  return { json: { ...seg, projections: {
    y5: ENGINE.projectedStats(byModel, seg.baseline, DEFAULTS.horizons.y5, DEFAULTS),
    y10: ENGINE.projectedStats(byModel, seg.baseline, DEFAULTS.horizons.y10, DEFAULTS),
  } } };
});
`,
  '04-ndvi.js': `
// W2 step 3. Input items: { segment, stats } where stats is the Copernicus Statistical API response
// (data[].interval.from, data[].outputs.ndvi.bands.B0.stats.mean). Output: segment with NDVI trend.
return $input.all().map((it) => {
  const seg = it.json.segment, rows = (it.json.stats && it.json.stats.data) || [];
  const series = rows.map((r) => ({ date: r.interval.from.slice(0, 10), ndvi: r.outputs && r.outputs.ndvi && r.outputs.ndvi.bands.B0.stats.mean }))
    .filter((p) => p.ndvi != null && !Number.isNaN(p.ndvi));
  return { json: { ...seg, ndviSeries: series, ndvi: ENGINE.ndviTrend(series) } };
});
`,
  '05-score.js': `
// W2 step 4. Input items: segments with baseline, projections, ndvi, slopePct, irradiance, substationKm.
// Optional: a learned model (ml/model.json) pasted into MODEL, or null for the hand-set weights.
const MODEL = null;
const cfg = DEFAULTS;
const out = $input.all().map((it) => {
  const s = it.json;
  s.risk = { y5: ENGINE.riskScore(s, 'y5', cfg, MODEL), y10: ENGINE.riskScore(s, 'y10', cfg, MODEL) };
  s.build = ENGINE.buildScore(s, s.risk.y10, cfg);
  s.money = { y5: ENGINE.moneyForSegment(s.risk.y5, 5, cfg), y10: ENGINE.moneyForSegment(s.risk.y10, 10, cfg) };
  s.needsExplanation = ['amber', 'red', 'red-uncertain'].includes(s.risk.y10.tier);
  s.needsWorkOrder = ['red', 'red-uncertain'].includes(s.risk.y10.tier);
  return { json: s };
});
return out;
`,
  '06-summary.js': `
// W2 step 5 / W6 API. Input: all scored segments. Output: one item, the corridor document the dashboard reads.
const segs = $input.all().map((i) => i.json);
return [{ json: {
  meta: { name: 'Corridor', synthetic: false, generatedAt: new Date().toISOString(), models: ['MRI_AGCM3_2_S', 'EC_Earth3P_HR', 'MPI_ESM1_2_XR'], note: 'Live n8n run' },
  config: DEFAULTS,
  segments: segs,
  summary: { y5: ENGINE.corridorSummary(segs, DEFAULTS, { years: 5 }), y10: ENGINE.corridorSummary(segs, DEFAULTS, { years: 10 }) },
} }];
`,
  '07-explain-prompt.js': `
// Before the AI node. Builds a prompt that only lets the model restate our numbers.
return $input.all().filter((i) => i.json.needsExplanation).map((i) => {
  const s = i.json, r = s.risk.y10;
  const facts = r.drivers.slice(0, 3).map((d) => \`\${d.label}: baseline \${d.base ?? '-'}, projected \${d.proj ?? '-'}, change \${d.change}\`).join('; ');
  return { json: { id: s.id, prompt:
    \`You explain a pipeline corridor risk score to an operations engineer. Use only these numbers, do not add any.
Segment \${s.id}, 10-year risk score \${r.score} (\${r.tier}), model agreement \${r.agreement}.
Drivers: \${facts}. Slope \${s.slopePct}%. NDVI 5-year change \${s.ndvi ? s.ndvi.change5yr : 'unknown'}.
Write exactly two sentences: what is driving the risk, and what a field crew should check first.\` } };
});
`,
};
for (const [name, body] of Object.entries(nodes)) write(`dist/n8n/${name}`, header + body.trimStart());
console.log('built dist/dashboard.html' + (snap ? ' (with offline snapshot)' : ' (no snapshot yet)') + (wiring.apiBase ? ', deploy/index.html' : '') + ', dist/dashboard-demo.html, dist/n8n/', Object.keys(nodes).join(', '));
